def digests(*paths: Path) -> str:
    return "".join(f"# lab/{p.name} sha256 {hashlib.sha256(p.read_bytes()).hexdigest()}\n" for p in paths)


def function_digest(path: Path, name: str) -> str:
    """The hash of one top-level function's source, so a change elsewhere in a big module leaves the files alone."""
    text = path.read_text(encoding="utf-8")
    start = text.index(f"\ndef {name}(")
    end = text.find("\n\n\n", start + 1)
    body = text[start:end if end > 0 else None]
    return f"# lab/{path.name} {name} sha256 {hashlib.sha256(body.encode()).hexdigest()}\n"


def candle_patterns() -> list[str]:
    import talib
    return talib.get_function_groups()["Pattern Recognition"]


def render(family: Path) -> dict[str, str]:
    """File name -> contents for every strategy in the family folder."""
    cfg = tomllib.loads((family / "family.toml").read_text(encoding="utf-8"))
    ex = cfg["exit"]
    common = {"header": HEADER, "timeframe": cfg["timeframe"], "startup": cfg["startup_candle_count"],
              "roi": json.dumps(ex["minimal_roi"]), "stoploss": ex["stoploss"], "hours": ex.get("time_stop_hours")}
    out = {}
    if cfg["kind"] == "candles":
        known = candle_patterns()
        skip = set(cfg["skip"]["bearish_only"])
        if unknown := skip - set(known):
            raise ValueError(f"{family}: not TA-Lib patterns: {sorted(unknown)}")
        for fn in known:
            if fn in skip:
                continue
            name = cfg["prefix"] + fn.removeprefix("CDL")
            out[f"{name}.py"] = TEMPLATE.format(
                **common, name=name, extra="", imports="import talib.abstract as ta",
                doc=f"Candlestick family: enter long when TA-Lib {fn} is above zero on the candle close.",
                signal=f"ta.{fn}(dataframe)")
    elif cfg["kind"] == "chart":
        digest = hashlib.sha256(PATTERNS.read_bytes()).hexdigest()
        for key, spec in cfg["strategies"].items():
            name = cfg["prefix"] + key
            args = ", ".join(f"{k}={json.dumps(v)}" for k, v in spec["args"].items())
            out[f"{name}.py"] = TEMPLATE.format(
                **common, name=name, extra=f"# lab/patterns.py sha256 {digest}\n", imports="from lab import patterns",
                doc=f"Chart-pattern family: enter long on patterns.{spec['call']}, on the close that completes it.",
                signal=f"patterns.{spec['call']}(dataframe, {args}).astype(int)")
    elif cfg["kind"] == "trend":
        for key, spec in cfg["strategies"].items():
            name = cfg["prefix"] + key
            out[f"{name}.py"] = TREND.format(
                **common, **cfg["sizing"], name=name, extra=digests(CHANNELS), lookbacks=json.dumps(spec["lookbacks"]),
                enter_at=spec["enter_at"], exit_at=spec["exit_at"],
                doc=f"Trend family: long-flat Donchian ensemble over {spec['lookbacks']} candles, entering at a score of "
                    f"{spec['enter_at']}, leaving at {spec['exit_at']}, stake cut to a {cfg['sizing']['vol_target']:.0%} vol target.")
    elif cfg["kind"] == "range":
        band = tomllib.loads(SUGGEST.read_text(encoding="utf-8"))["confidence"]["trend_band"]
        for key, spec in cfg["strategies"].items():
            name = cfg["prefix"] + key
            out[f"{name}.py"] = RANGE.format(
                **common, **spec, name=name, extra=digests(CHANNELS) + function_digest(METRICS, "trend_buckets"), band=band,
                doc=f"Range family: buy a close {spec['z_enter']} deviations under its {spec['window']}-candle mean "
                    f"while BTC is flat (within {band:.0%} of its 200-day mean), sell back at z {spec['z_exit']}.")
    else:
        raise ValueError(f"{family}: unknown kind {cfg['kind']!r}")
    return out


def families() -> list[Path]:
    return sorted(p.parent for root in ROOTS for p in root.glob("*/family.toml"))


def orphans(family: Path, want: dict[str, str]) -> list[Path]:
    """Generated files render no longer writes."""
    return [p for p in family.glob("*.py") if p.name not in want and p.read_text(encoding="utf-8").startswith(HEADER)]


def stale(family: Path) -> list[str]:
    """Files that differ from what render writes, or generated files it no longer writes."""
    want = render(family)
    bad = [n for n, text in want.items() if not (family / n).exists() or (family / n).read_text(encoding="utf-8") != text]
    return sorted(bad + [p.name for p in orphans(family, want)])


def write(family: Path) -> int:
    want = render(family)
    for p in orphans(family, want):
        p.unlink()
    for n, text in want.items():
        (family / n).write_text(text, encoding="utf-8")
    return len(want)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="report stale files and exit 1 instead of writing")
    args = ap.parse_args(argv)
    bad = 0
    for fam in families():
        if args.check:
            for n in stale(fam):
                print(f"stale: {(fam / n).relative_to(REPO)}")
                bad += 1
        else:
            print(f"{fam.relative_to(REPO)}: {write(fam)} strategies")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
