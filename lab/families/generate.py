import json
import hashlib
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ROOTS = (REPO / "lab" / "families", REPO / "user_data" / "strategies")
PATTERNS = REPO / "lab" / "patterns.py"
CHANNELS = REPO / "lab" / "channels.py"
METRICS = REPO / "lab" / "metrics.py"
