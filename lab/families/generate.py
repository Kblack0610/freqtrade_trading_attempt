"""Write a strategy family's files from its family.toml.

    python lab/families/generate.py            # rewrite every family
    python lab/families/generate.py --check    # exit 1 if any family's files are not what it would write

A family is a folder holding a family.toml, under lab/families/ while staged or under
user_data/strategies/ once switched on. Each strategy gets its own file with a literal
`class <Name>(`, because freqtrade loads a strategy by name only from a file containing that text:
classes built in a loop list fine but never load. Each file also carries every number it uses, and
a chart file the hash of lab/patterns.py, so the analysis, which keys its cache on the strategy
file's hash, reruns a strategy whenever its exit, its parameters or its pattern code change.
"""

import argparse
import json
import hashlib
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ROOTS = (REPO / "lab" / "families", REPO / "user_data" / "strategies")
PATTERNS = REPO / "lab" / "patterns.py"
HEADER = "# Generated by lab/families/generate.py from family.toml: edit that and rerun it, not this file."

TEMPLATE = '''{header}
{extra}"""{doc}"""

from datetime import timedelta

{imports}
from pandas import DataFrame

from freqtrade.strategy import IStrategy


class {name}(IStrategy):
    INTERFACE_VERSION = 3
    timeframe = "{timeframe}"
    can_short = False
    startup_candle_count = {startup}
    minimal_roi = {roi}
    stoploss = {stoploss}
    max_hold = timedelta(hours={hours})

    def populate_indicators(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        dataframe["pattern"] = {signal}
        return dataframe

    def populate_entry_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        dataframe.loc[dataframe["pattern"] > 0, "enter_long"] = 1
        return dataframe

    def populate_exit_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        return dataframe

    def custom_exit(self, pair: str, trade, current_time, current_rate, current_profit, **kwargs):
        if current_time - trade.open_date_utc >= self.max_hold:
            return "time_stop"
        return None
'''


def candle_patterns() -> list[str]:
    import talib
    return talib.get_function_groups()["Pattern Recognition"]


def render(family: Path) -> dict[str, str]:
    """File name -> contents for every strategy in the family folder."""
    cfg = tomllib.loads((family / "family.toml").read_text(encoding="utf-8"))
    ex = cfg["exit"]
    common = {"header": HEADER, "timeframe": cfg["timeframe"], "startup": cfg["startup_candle_count"],
              "roi": json.dumps(ex["minimal_roi"]), "stoploss": ex["stoploss"], "hours": ex["time_stop_hours"]}
    out = {}
    if cfg["kind"] == "candles":
        known = candle_patterns()
        skip = set(cfg["skip"]["bearish_only"])
        if unknown := skip - set(known):
            raise ValueError(f"{family}: not TA-Lib patterns: {sorted(unknown)}")
        for fn in known:
            if fn in skip:
                continue
            name = cfg["prefix"] + fn.removeprefix("CDL")
            out[f"{name}.py"] = TEMPLATE.format(
                **common, name=name, extra="", imports="import talib.abstract as ta",
                doc=f"Candlestick family: enter long when TA-Lib {fn} is above zero on the candle close.",
                signal=f"ta.{fn}(dataframe)")
    elif cfg["kind"] == "chart":
        digest = hashlib.sha256(PATTERNS.read_bytes()).hexdigest()
        for key, spec in cfg["strategies"].items():
            name = cfg["prefix"] + key
            args = ", ".join(f"{k}={json.dumps(v)}" for k, v in spec["args"].items())
            out[f"{name}.py"] = TEMPLATE.format(
                **common, name=name, extra=f"# lab/patterns.py sha256 {digest}\n", imports="from lab import patterns",
                doc=f"Chart-pattern family: enter long on patterns.{spec['call']}, on the close that completes it.",
                signal=f"patterns.{spec['call']}(dataframe, {args}).astype(int)")
    else:
        raise ValueError(f"{family}: unknown kind {cfg['kind']!r}")
    return out


def families() -> list[Path]:
    return sorted(p.parent for root in ROOTS for p in root.glob("*/family.toml"))


def orphans(family: Path, want: dict[str, str]) -> list[Path]:
    """Generated files render no longer writes."""
    return [p for p in family.glob("*.py") if p.name not in want and p.read_text(encoding="utf-8").startswith(HEADER)]


def stale(family: Path) -> list[str]:
    """Files that differ from what render writes, or generated files it no longer writes."""
    want = render(family)
    bad = [n for n, text in want.items() if not (family / n).exists() or (family / n).read_text(encoding="utf-8") != text]
    return sorted(bad + [p.name for p in orphans(family, want)])


def write(family: Path) -> int:
    want = render(family)
    for p in orphans(family, want):
        p.unlink()
    for n, text in want.items():
        (family / n).write_text(text, encoding="utf-8")
    return len(want)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="report stale files and exit 1 instead of writing")
    args = ap.parse_args(argv)
    bad = 0
    for fam in families():
        if args.check:
            for n in stale(fam):
                print(f"stale: {(fam / n).relative_to(REPO)}")
                bad += 1
        else:
            print(f"{fam.relative_to(REPO)}: {write(fam)} strategies")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
