"""Write a strategy family's files from its family.toml.

    python lab/families/generate.py            # rewrite every family
    python lab/families/generate.py --check    # exit 1 if any family's files are not what it would write

A family is a folder holding a family.toml, under lab/families/ while staged or under
user_data/strategies/ once switched on. Each strategy gets its own file with a literal
`class <Name>(`, because freqtrade loads a strategy by name only from a file containing that text:
classes built in a loop list fine but never load. Each file also carries every number it uses, and
a chart, signal, trend or range file the hash of the lab modules it calls, so the analysis, which keys its cache on the
strategy file's hash, reruns a strategy whenever its exit, its parameters or its pattern code change.

A family's `ladder` lists the timeframes each strategy runs on (a strategy's own `timeframes` overrides it). The
family's `timeframe` keeps the plain name, so its files and their cached results stay as they were; every other rung
is `<Name>_<timeframe>`. With `scale_exit` (the default) a rung's exit keeps its shape in candles and in
volatility: hold times and ROI steps scale with the candle length, the stoploss and ROI targets with its square root.
"""

