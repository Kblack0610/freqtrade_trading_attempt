#!/usr/bin/env bash
# Regenerate lab/requirements.lock from lab/requirements.txt: every package the image adds on top of the
# Freqtrade base, transitive ones included, pinned with hashes. The Dockerfile installs only the lock
# (--require-hashes --no-deps), so a build never resolves a version no commit chose.
# Resolved against the base image named by the Dockerfile's FREQTRADE_IMAGE default: a package the base
# already ships is held at the base's version and left out of the lock, so the install never replaces one.
# Run it after editing lab/requirements.txt or bumping the base digest; lab/tests/test_requirements_lock.py
# fails when a top-level pin and the lock disagree.
# Needs docker and uv.
set -euo pipefail
cd "$(dirname "$0")/.."

base=$(sed -n 's/^ARG FREQTRADE_IMAGE=//p' Dockerfile)
[ -n "$base" ] || { echo "no FREQTRADE_IMAGE default in Dockerfile" >&2; exit 1; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

docker run --rm --entrypoint sh "$base" -c 'python -c "import sys; print(\"%d.%d\" % sys.version_info[:2])"; pip freeze' >"$tmp/freeze"
py=$(head -n 1 "$tmp/freeze")
# The base's own packages, minus freqtrade itself (an editable install with no version).
tail -n +2 "$tmp/freeze" | grep -E '^[A-Za-z0-9][^ ]*==' >"$tmp/base.txt"
no_emit=()
while IFS= read -r name; do no_emit+=(--no-emit-package "$name"); done < <(cut -d= -f1 "$tmp/base.txt")

uv pip compile lab/requirements.txt -c "$tmp/base.txt" \
  --python-version "$py" --python-platform x86_64-manylinux_2_28 \
  --generate-hashes --no-header --no-annotate "${no_emit[@]}" -o "$tmp/lock"

{
  echo "# Generated by ci/lock_requirements.sh from lab/requirements.txt against $base."
  echo "# Do not edit by hand: change lab/requirements.txt and re-run the script."
  cat "$tmp/lock"
} >lab/requirements.lock
echo "wrote lab/requirements.lock"
